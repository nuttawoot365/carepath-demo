export const langMeta = (code: string): LangMeta => LANGS.find((l) => l.code === code) ?? LANGS[0];

/** t('walk', {m: 25}) — คีย์ที่ไม่มีในภาษานั้นถอยไปใช้ไทย แล้วค่อยคืนคีย์เดิม */
export function translator(lang: string) {
  return (key: string, params: Record<string, unknown> = {}): string => {
    const template = DICT[lang]?.[key] ?? DICT.th[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (_match, name: string) => String(params[name] ?? ''));
  };
}

export const sentenceCase = (lang: string, text: string): string =>
  CAPITALISED.has(lang) ? text.charAt(0).toUpperCase() + text.slice(1) : text;
